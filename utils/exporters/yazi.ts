import type { ThemePalette, ExportResult } from '../types'
import { ensureContrast } from '../contrast'

/**
 * Generates a Yazi file manager theme in TOML format
 * Ensures proper contrast ratios for accessibility
 * @param palette - Semantic color palette
 * @param themeName - Name of the theme
 * @returns Yazi theme.toml file content
 */
export function exportYazi(palette: ThemePalette, themeName: string = 'vulpes'): ExportResult {
  // Ensure fallback file color has sufficient contrast against background
  // Critical for accessibility in light themes
  const fallbackFileFg = ensureContrast(palette.bg, palette.fg)
  const content = `# ${themeName} - Yazi Theme
# Generated by vulpes-theme-lab

[mgr]
cwd = { fg = "${palette.base}" }

# Find
find_keyword  = { fg = "${palette.warning}", italic = true }
find_position = { fg = "${palette.info}", bg = "reset", italic = true }

# Marker
marker_selected = { fg = "${palette.success}", bg = "${palette.success}" }
marker_copied   = { fg = "${palette.warning}", bg = "${palette.warning}" }
marker_cut      = { fg = "${palette.error}", bg = "${palette.error}" }

# Border
border_symbol = "│"
border_style  = { fg = "${palette.bg_alt}" }

# Highlighting
syntect_theme = ""

# Hovered row in each column (yazi 26: was mgr.hovered / mgr.preview_hovered)
[indicator]
parent  = { fg = "${palette.base}", bg = "${palette.bg_alt}" }
current = { fg = "${palette.bg}", bg = "${palette.base}" }
preview = { underline = true }

[mode]
normal_main = { fg = "${palette.bg}", bg = "${palette.base}", bold = true }
normal_alt  = { fg = "${palette.base}", bg = "${palette.bg_alt}" }
select_main = { fg = "${palette.bg}", bg = "${palette.success}", bold = true }
select_alt  = { fg = "${palette.success}", bg = "${palette.bg_alt}" }
unset_main  = { fg = "${palette.bg}", bg = "${palette.error}", bold = true }
unset_alt   = { fg = "${palette.error}", bg = "${palette.bg_alt}" }

[status]
overall   = { fg = "${palette.fg}", bg = "${palette.bg}" }
sep_left  = { open = "", close = "" }
sep_right = { open = "", close = "" }

# Permissions
perm_type  = { fg = "${palette.success}" }
perm_read  = { fg = "${palette.warning}" }
perm_write = { fg = "${palette.error}" }
perm_exec  = { fg = "${palette.info}" }
perm_sep   = { fg = "${palette.comment}" }

# Progress
progress_label  = { fg = "${palette.fg}", bold = true }
progress_normal = { fg = "${palette.base}", bg = "${palette.bg_alt}" }
progress_error  = { fg = "${palette.error}", bg = "${palette.bg_alt}" }

[tabs]
active   = { fg = "${palette.bg}", bg = "${palette.base}" }
inactive = { fg = "${palette.comment}", bg = "${palette.bg_alt}" }

[input]
border   = { fg = "${palette.base}" }
title    = {}
value    = {}
selected = { reversed = true }

[pick]
border   = { fg = "${palette.base}" }
active   = { fg = "${palette.base}" }
inactive = {}

[tasks]
border  = { fg = "${palette.base}" }
title   = {}
hovered = { underline = true }

[which]
border          = { fg = "${palette.base}" }
mask            = { bg = "${palette.bg_alt}" }
cand            = { fg = "${palette.base}" }
rest            = { fg = "${palette.comment}" }
desc            = { fg = "${palette.fg}" }
separator       = "  "
separator_style = { fg = "${palette.comment}" }

[help]
border  = { fg = "${palette.base}" }
chord   = { fg = "${palette.success}" }
action  = { fg = "${palette.info}" }
hovered = { bg = "${palette.bg_alt}", bold = true }

[filetype]

rules = [
\t# Images
\t{ mime = "image/*", fg = "${palette.info}" },

\t# Videos
\t{ mime = "video/*", fg = "${palette.warning}" },
\t{ mime = "audio/*", fg = "${palette.warning}" },

\t# Archives
\t{ mime = "application/zip",             fg = "${palette.error}" },
\t{ mime = "application/gzip",            fg = "${palette.error}" },
\t{ mime = "application/x-tar",           fg = "${palette.error}" },
\t{ mime = "application/x-bzip",          fg = "${palette.error}" },
\t{ mime = "application/x-bzip2",         fg = "${palette.error}" },
\t{ mime = "application/x-7z-compressed", fg = "${palette.error}" },
\t{ mime = "application/x-rar",           fg = "${palette.error}" },

\t# Documents
\t{ mime = "application/pdf", fg = "${palette.base}" },

\t# Fallback - ensures sufficient contrast for accessibility
\t{ url = "*", fg = "${fallbackFileFg}" },
\t{ url = "*/", fg = "${palette.base}" }
]
`

  return {
    filename: 'theme.toml',
    content,
    format: 'yazi',
  }
}
