/**
 * Export every Vulpes monthly preset, in both dark and light mode, to every
 * supported terminal/editor/tool format, plus a non-destructive install.sh
 * and a README per app, zipped per preset and as one all-in-one archive.
 *
 * Run with:  npm run export:all
 * (wraps `vite-node -c vitest.config.ts scripts/export-all.ts` so the `~`
 * alias resolves the same way it does in the Nuxt app and the test suite)
 *
 * Output: dist-themes/<preset-id>/<mode>/<app>/<files + README.md>
 *         dist-themes/<preset-id>/install.sh
 *         dist-themes/<preset-id>.zip
 *         dist-themes/install.sh                 (top-level dispatcher)
 *         dist-themes/vulpes-all-themes.zip       (everything, no nested zips)
 */
import { mkdirSync, writeFileSync, chmodSync, rmSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

import { VULPES_MONTHLY_PRESETS, type ThemePreset } from '../utils/presets'
import { generateThemeVariant, presetToThemeState } from '../utils/generateTheme'
import {
  createSemanticPalette,
  exportGhostty,
  exportNeovim,
  exportBat,
  exportYazi,
  exportLazygit,
  exportZsh,
  exportTweakcc,
  exportNeomutt,
  exportWezterm,
  exportAlacritty,
  exportTailwind,
  exportObsidian,
  type ExportResult,
  type ThemePalette,
} from '../utils/exporters'
import { serializeItermTheme } from '../utils/iterm'
import { serializeTmuxTheme } from '../utils/tmux'
import { generateTweakccInstructions } from '../utils/exporters/tweakcc'
import { APP_IDS, renderAppReadme, renderInstallScript, renderTopLevelInstallScript } from '../utils/installer'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const OUT_DIR = join(ROOT, 'dist-themes')

type Mode = 'dark' | 'light'

// Exporters that take (palette, themeName) and return ExportResult, keyed by
// the same app id used throughout utils/installer.ts. Intentionally only
// imports/calls the existing exporters -- no color mapping is touched here.
const EXPORTERS: Record<string, (palette: ThemePalette, name: string) => ExportResult> = {
  ghostty: exportGhostty,
  wezterm: exportWezterm,
  alacritty: exportAlacritty,
  nvim: exportNeovim,
  bat: exportBat,
  lazygit: exportLazygit,
  yazi: exportYazi,
  zsh: exportZsh,
  neomutt: exportNeomutt,
  tweakcc: exportTweakcc,
  tailwind: exportTailwind,
  obsidian: exportObsidian,
}

function writeFile(path: string, content: string): void {
  mkdirSync(join(path, '..'), { recursive: true })
  writeFileSync(path, content)
}

function hasPlaceholders(content: string): string[] {
  const issues: string[] = []
  if (content.includes('undefined')) issues.push('undefined')
  if (content.includes('NaN')) issues.push('NaN')
  if (content.includes('[object Object]')) issues.push('[object Object]')
  return issues
}

function zipDir(dirToZip: string, zipPath: string, excludeGlobs: string[] = []): void {
  if (existsSync(zipPath)) rmSync(zipPath)
  const args = ['-r', '-q', zipPath, '.']
  for (const glob of excludeGlobs) args.push('-x', glob)
  execFileSync('zip', args, { cwd: dirToZip, stdio: ['ignore', 'pipe', 'pipe'] })
}

function exportPreset(preset: ThemePreset): void {
  const presetDir = join(OUT_DIR, preset.id)
  const modes: Mode[] = ['dark', 'light']
  let fileCount = 0
  const allIssues: string[] = []

  for (const mode of modes) {
    const state = presetToThemeState(preset)
    const themeColors = generateThemeVariant(state, mode)
    const palette = createSemanticPalette(themeColors, mode)
    const themeName = `${preset.id}-${mode}`
    const modeDir = join(presetDir, mode)

    for (const [appId, exporter] of Object.entries(EXPORTERS)) {
      const result = exporter(palette, themeName)
      const issues = hasPlaceholders(result.content)
      if (issues.length > 0) {
        allIssues.push(`${preset.id}/${mode}/${appId}: ${issues.join(', ')}`)
      }
      writeFile(join(modeDir, appId, result.filename), result.content)
      fileCount++

      // tweakcc ships a second instructions file generated by its own
      // exporter module (generateTweakccInstructions) -- reused, not
      // reimplemented.
      if (appId === 'tweakcc') {
        const instructions = generateTweakccInstructions(themeName, palette)
        writeFile(join(modeDir, appId, 'INSTRUCTIONS.md'), instructions)
      }
    }

    // iterm + tmux are not in the shared EXPORTERS registry (they predate
    // the ThemePalette/ExportResult convention), but pages/index.vue wires
    // them in exactly this shape -- same here.
    const itermName = `${themeName}.itermcolors`
    const itermContent = serializeItermTheme(themeColors, themeName)
    writeFile(join(modeDir, 'iterm', itermName), itermContent)
    fileCount++

    const tmuxName = `${themeName}.tmux.conf`
    const tmuxContent = serializeTmuxTheme(themeColors, themeName)
    writeFile(join(modeDir, 'tmux', tmuxName), tmuxContent)
    fileCount++
  }

  // One README per app (mode-agnostic -- covers both dark/light files).
  const allApps = [...APP_IDS]
  for (const appId of allApps) {
    const readme = renderAppReadme(appId as (typeof APP_IDS)[number], preset.id)
    writeFile(join(presetDir, 'dark', appId, 'README.md'), readme)
    writeFile(join(presetDir, 'light', appId, 'README.md'), readme)
    fileCount += 2
  }

  // install.sh
  const installScriptPath = join(presetDir, 'install.sh')
  writeFile(installScriptPath, renderInstallScript(preset.id))
  chmodSync(installScriptPath, 0o755)

  // zip this preset's folder (excluding any zip files, so the all-in-one zip
  // below doesn't end up with zips-of-zips)
  zipDir(presetDir, join(OUT_DIR, `${preset.id}.zip`), ['*.zip'])

  if (allIssues.length > 0) {
    console.error(`  ! placeholder values found:\n    ${allIssues.join('\n    ')}`)
  }
  console.log(`  ${preset.id}: ${fileCount} files`)
}

function main(): void {
  console.log(`Exporting ${VULPES_MONTHLY_PRESETS.length} presets x 2 modes x ${Object.keys(EXPORTERS).length + 2} apps...`)
  mkdirSync(OUT_DIR, { recursive: true })

  for (const preset of VULPES_MONTHLY_PRESETS) {
    exportPreset(preset)
  }

  const topInstallPath = join(OUT_DIR, 'install.sh')
  writeFile(topInstallPath, renderTopLevelInstallScript())
  chmodSync(topInstallPath, 0o755)

  zipDir(OUT_DIR, join(OUT_DIR, 'vulpes-all-themes.zip'), ['*.zip'])

  console.log(`\nDone. Output: ${OUT_DIR}`)
}

main()
